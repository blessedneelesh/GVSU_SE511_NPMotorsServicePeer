    ADD COLUMN transfer_reference VARCHAR(50),
    ADD CONSTRAINT uq_transaction_transfer_side
        UNIQUE (transfer_reference, direction),
    ADD CONSTRAINT ck_transaction_transfer_type
        CHECK (transfer_reference IS NULL OR type = 'Transfer');

