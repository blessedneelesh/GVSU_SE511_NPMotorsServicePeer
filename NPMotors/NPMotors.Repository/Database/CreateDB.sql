-- ---------------------------------------------------------------------
-- Bank statement
-- ---------------------------------------------------------------------
-- Statement-only adjustment : transaction_id NULL, match_status = 'Unmatched',
--                             source = 'Manual', book balance unchanged
-- Add & Post to Books       : transaction_id set, match_status = 'Matched',
--                             book balance updated
-- running_balance is calculated from ordered statement lines.
CREATE TABLE bank_statement_line (
    id               BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id   BIGINT    UNIQUE REFERENCES "transaction" (id),
    bank_account_id  BIGINT    NOT NULL REFERENCES bank_account (id),
    posted_date      DATE,
    bank_reference   VARCHAR(100),
    description      VARCHAR(500),
    party            VARCHAR(255),
    type             VARCHAR(30),
    adjustment_type  VARCHAR(30),
    direction        direction_enum NOT NULL,
    deposit          NUMERIC(14,2)  NOT NULL DEFAULT 0,
    withdrawal       NUMERIC(14,2)  NOT NULL DEFAULT 0,
    running_balance  NUMERIC(14,2),
    statement_status VARCHAR(30),
    match_status     VARCHAR(30),
    source           VARCHAR(30),
    notes            VARCHAR(1000),
    created_at       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Direction rules
    CONSTRAINT ck_bsl_direction CHECK (
        (direction = 'in'  AND deposit > 0 AND withdrawal = 0) OR
        (direction = 'out' AND deposit = 0 AND withdrawal > 0)
    )
);

-- v3 Story 24 AC5: a bank reference is unique within the account when
