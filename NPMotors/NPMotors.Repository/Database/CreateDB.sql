-- v3 Story 23: a reversal references the transaction it reverses.
-- UNIQUE: the same transaction cannot be reversed twice.
ALTER TABLE "transaction"
    ADD COLUMN reverses_transaction_id BIGINT,
    ADD CONSTRAINT fk_transaction_reverses
        FOREIGN KEY (reverses_transaction_id) REFERENCES "transaction" (id),
    ADD CONSTRAINT uq_transaction_reverses UNIQUE (reverses_transaction_id),
    ADD CONSTRAINT ck_transaction_not_self_reversal
        CHECK (reverses_transaction_id <> id);

-- v3 Story 23 AC1: a reversal requires a reason. The reason is set exactly
--    when the transaction reverses another one.
ALTER TABLE "transaction"
    ADD COLUMN reversal_reason VARCHAR(500),
    ADD CONSTRAINT ck_transaction_reversal_reason CHECK (
        (reverses_transaction_id IS NULL AND reversal_reason IS NULL)
        OR (reverses_transaction_id IS NOT NULL AND reversal_reason IS NOT NULL)
    );

-- v3 Story 10: both sides of a transfer share one reference.
